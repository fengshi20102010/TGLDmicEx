#!/usr/bin/env python3
"""Turn a SOF dmesg capture (sof_debug=0xa00 + dyndbg) into a C replay table.

usage:
  extract-ipc.py dmesg-capture-pcm6-S32_LE.txt > kext/TGLDmic/IpcReplay.hpp
  extract-ipc.py --suffix 2ch --source "Lenovo XiaoXin Pro 13 2020 (2 DMIC)" --channels 2 \\
                 --volume 0x10000 dmesg-capture-pcm6-S32_LE.txt > kext/TGLDmic/IpcReplay2ch.hpp

Each IPC3 message = 8-byte sof_ipc_cmd_hdr {size, cmd} + payload. The kernel log
prints the payload *after* the header, so we rebuild the header here.

Options:
  --suffix S    name the tables kIpc<S>_setup ... (default: kIpc_setup ..., the original 4ch table)
  --source TXT  machine the capture came from (header comment)
  --channels N  channel count in the header comment (the table itself comes from the capture)
  --volume Q16  overwrite the per-channel values of every COMP_SET_VALUE / SOF_CTRL_CMD_VOLUME message.
                The capture carries the Linux mixer state of that session (it may be far from 0 dB);
                0x10000 = unity gain. Leave unset to keep the captured values.
Global trace messages (SOF_IPC_GLB_TRACE_MSG, 0x4xxxxxxx) are dropped: they configure Linux's
trace DMA, which the kext never sets up.
"""
import argparse, re, sys

CMD_NAMES = {
    0x30010000: "TPLG_COMP_NEW", 0x30020000: "TPLG_COMP_FREE", 0x30030000: "TPLG_COMP_CONNECT",
    0x30100000: "TPLG_PIPE_NEW", 0x30110000: "TPLG_PIPE_FREE", 0x30130000: "TPLG_PIPE_COMPLETE",
    0x30200000: "TPLG_BUFFER_NEW", 0x30210000: "TPLG_BUFFER_FREE",
    0x50010000: "COMP_SET_VALUE", 0x50030000: "COMP_SET_DATA",
    0x60010000: "STREAM_PCM_PARAMS", 0x60030000: "STREAM_PCM_FREE",
    0x60040000: "STREAM_TRIG_START", 0x60050000: "STREAM_TRIG_STOP",
    0x80010000: "DAI_CONFIG",
}
GLB_TYPE_MASK, GLB_TRACE_MSG = 0xF0000000, 0x40000000
# sof_ipc_ctrl_data (payload words, i.e. after the 8-byte header): [0] error [1] comp_id [2] type
# [3] cmd [4] index ... [12] num_elems ... then chanv[] = {channel, value} pairs at the end.
CTRL_CMD_IDX, CTRL_NUM_ELEMS_IDX, SOF_CTRL_CMD_VOLUME = 3, 12, 0


def parse(path):
    """'widget X setup complete' is logged AFTER that widget's IPCs; routes/triggers BEFORE."""
    msgs, cur, pending, ctx = [], None, [], ""
    for line in open(path, errors="replace"):
        m = re.search(r"widget (\S+) (setup complete|freed)", line)
        if m:
            for x in pending: x["ctx"] = f"widget {m.group(1)}"
            pending = []
            continue
        m = re.search(r"(setting up route .*|Entry: (?:trigger \(cmd: \d\)|hw_free|hw_params)|tplg: complete pipeline .*)", line)
        if m:
            ctx = m.group(1).strip(); pending = []
            continue
        m = re.search(r"ipc tx: (0x[0-9a-f]+)$", line.strip())
        if m:
            cur = {"cmd": int(m.group(1), 16), "words": [], "ctx": ctx}
            msgs.append(cur); pending.append(cur)
            continue
        m = re.search(r"Message payload: ([0-9a-f]{8}): ((?:[0-9a-f]{8} ?)+)", line)
        if m and cur is not None:
            cur["words"] += [int(w, 16) for w in m.group(2).split()]
    return msgs


def set_volume(m, q16):
    """Overwrite the chanv[] values of a volume COMP_SET_VALUE. Returns True if patched."""
    w = m["words"]
    if m["cmd"] != 0x50010000 or len(w) <= CTRL_NUM_ELEMS_IDX or w[CTRL_CMD_IDX] != SOF_CTRL_CMD_VOLUME:
        return False
    n = w[CTRL_NUM_ELEMS_IDX]
    base = len(w) - 2 * n
    if n < 1 or base <= CTRL_NUM_ELEMS_IDX:
        return False
    for i in range(n):
        w[base + 2 * i + 1] = q16
    return True


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("dmesg")
    ap.add_argument("--suffix", default="")
    ap.add_argument("--source", default="HP EliteBook 840 G8")
    ap.add_argument("--channels", type=int, default=4)
    ap.add_argument("--volume", type=lambda s: int(s, 0), default=None)
    a = ap.parse_args()

    msgs = [m for m in parse(a.dmesg) if (m["cmd"] & GLB_TYPE_MASK) != GLB_TRACE_MSG]
    start = next(i for i, m in enumerate(msgs) if m["cmd"] == 0x60040000)
    stop = next(i for i, m in enumerate(msgs) if m["cmd"] == 0x60050000)
    phases = {"setup": msgs[:start], "start": msgs[start:start + 1],
              "stop": msgs[stop:stop + 2], "teardown": msgs[stop + 2:]}
    patched = sum(set_volume(m, a.volume) for m in phases["setup"]) if a.volume is not None else 0
    if a.volume is not None and not patched:
        sys.exit("--volume given but no volume COMP_SET_VALUE found in the setup phase")

    sfx = a.suffix
    print(f"// Generated by linux/extract-ipc.py from a Linux SOF v2.2 capture on {a.source}")
    print(f"// Pipeline 10: DMIC0.IN -> EQIIR10.0 (highpass) -> Dmic0 (volume) -> PCM6C host, 48 kHz, {a.channels} ch, S32_LE")
    if patched:
        print(f"// Dmic0 volume overridden to 0x{a.volume:x} (Q16, 0x10000 = 0 dB) in {patched} message(s); "
              "the captured value was the Linux session's mixer state")
    print("#pragma once")
    print('#include "IpcCommon.hpp"\n')
    for ph, lst in phases.items():
        for i, m in enumerate(lst):
            size = 8 + 4 * len(m["words"])
            w = [size, m["cmd"]] + m["words"]
            body = ", ".join("0x%08x" % x for x in w)
            print(f"// {ph}[{i}] {CMD_NAMES.get(m['cmd'], hex(m['cmd']))}  ({m['ctx']})")
            print(f"static const uint32_t ipc{sfx}_{ph}_{i}[] = {{ {body} }};")
    print()
    for ph, lst in phases.items():
        print(f"static const IpcMsg kIpc{sfx}_{ph}[] = {{")
        for i, m in enumerate(lst):
            patch = "kPatchPcmParams" if m["cmd"] == 0x60010000 else "kPatchNone"
            name = CMD_NAMES.get(m["cmd"], "UNKNOWN")
            print(f"  {{ 0x{m['cmd']:08x}, {len(m['words']) + 2}, {patch}, ipc{sfx}_{ph}_{i}, \"{name}\" }},")
        print("};")


if __name__ == "__main__":
    main()
